/** A guest's next line: from `pool`, never the same as the guest's last
 *  one, picked with the run's seeded `r`. */
export function nextLine(pool: readonly string[], r: () => number, last: string | null = null): string {
  if (pool.length === 0) return "Hello.";
  for (let i = 0; i < 4; i++) {
    const line = pool[Math.floor(r() * pool.length)]!;
    if (line !== last || pool.length === 1) return line;
  }
  return pool[0]!;
}

/** A `--lines` file: a JSON list of strings, or `{lines: [...]}`. Null when
 *  it holds no usable line. */
export function readLines(doc: unknown): string[] | null {
  const raw = Array.isArray(doc) ? doc : (doc as { lines?: unknown } | null)?.lines;
  if (!Array.isArray(raw)) return null;
  const out = raw.filter((l): l is string => typeof l === "string" && l.trim() !== "").map((l) => l.trim().slice(0, 500));
  return out.length === 0 ? null : out;
}
